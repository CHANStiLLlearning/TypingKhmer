export const ENGLISH_CHAR_TO_KEY_MAP = new Map();

Object.values(ENGLISH_KEY_MAP).forEach((key) => {
  if (key.normal?.char) {
    ENGLISH_CHAR_TO_KEY_MAP.set(key.normal.char, {
      code: key.code,
      layer: 'normal',
      modifier: null,
      keyData: key,
    });
  }
  if (key.shift?.char) {
    ENGLISH_CHAR_TO_KEY_MAP.set(key.shift.char, {
      code: key.code,
      layer: 'shift',
      modifier: 'Shift',
      keyData: key,
    });
  }
});

