/**
 * Reverse mapping index: Character -> { code, layer, modifierRequired, keyData }
 */
export const CHAR_TO_KEY_MAP = new Map();

Object.values(KHMER_KEY_MAP).forEach((key) => {
  if (key.normal?.char) {
    CHAR_TO_KEY_MAP.set(key.normal.char, {
      code: key.code,
      layer: 'normal',
      modifier: null,
      keyData: key,
    });
  }
  if (key.shift?.char && !CHAR_TO_KEY_MAP.has(key.shift.char)) {
    CHAR_TO_KEY_MAP.set(key.shift.char, {
      code: key.code,
      layer: 'shift',
      modifier: 'Shift',
      keyData: key,
    });
  }
  if (key.altGr?.char && !CHAR_TO_KEY_MAP.has(key.altGr.char)) {
    CHAR_TO_KEY_MAP.set(key.altGr.char, {
      code: key.code,
      layer: 'altGr',
      modifier: 'AltGr',
      keyData: key,
    });
  }
});

// Also map zero-width space (\u200B) and non-breaking space (\u00A0) to Space
CHAR_TO_KEY_MAP.set('\u200B', {
  code: 'Space',
  layer: 'normal',
  modifier: null,
  keyData: KHMER_KEY_MAP['Space'],
});
CHAR_TO_KEY_MAP.set('\u00A0', {
  code: 'Space',
  layer: 'altGr',
  modifier: 'AltGr',
  keyData: KHMER_KEY_MAP['Space'],
});

